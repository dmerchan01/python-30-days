print("Hello World!\n")

# Operators
print("Operators")
print(f"3 + 3 = {3 + 3}")      # Addition (+)   
print(f"3 - 3 =  {3 - 3}")     # Subtraction (-)
print(f"3 * 3 =  {3 * 3}")     # Multiplication (*)
print(f"3 / 3 =  {3 / 3}")     # Divisiopn (/)
print(f"3 ** 3 =  {3 ** 2}")   # Exponential (**)
print(f"3 % 3 =  {3 % 2}")     # Modulus (%)
print(f"3 // 3 =  {3 // 2}")   # Floor Division (//)

# Data Types
print("\nData Types")
print(f"10 is a {type(10)}")                                           # Int
print(f"3.14 is a {type(3.14)}")                                       # Float
print(f"1 + 3j is a {type(1 + 3j)}")                                   # Complex
print(f"Diego is a {type('Diego')}")                                   # String
print(f"[1,2,3] is a {type([1,2,3])}")                                 # List
print(f"{ {'name': 'Hernando'} } is a {type({'name': 'Hernando'})}")   # Dictionary
print(f"{ { 9.8,3.1,6.9 } } is a {type({9.8,3.1,6.9})}")               # Tuple
